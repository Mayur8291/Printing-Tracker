/** Actual hosted SDK journey. Credentials and emailed code enter only on stdin. */
import assert from 'node:assert/strict';
import {createInterface} from 'node:readline';
import {createClient} from '@supabase/supabase-js';
import {createSquadClient,SquadError} from '../../packages/shared/squad.js';
const lines=createInterface({input:process.stdin,terminal:false})[Symbol.asyncIterator]();
const read=async()=>JSON.parse((await lines.next()).value);
const cfg=await read();
const client=()=>createClient(cfg.url,cfg.anon,{auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false}});
const old=client(),guest=client(),current=client(),probe=client();
const email=cfg.customer.email;const {data,error}=await old.auth.signInWithPassword(cfg.customer);assert.equal(error,null);
const previous=data.session;const sdk=createSquadClient(guest),oldSdk=createSquadClient(old);
const requested=await sdk.requestRecovery(email,cfg.request_id);assert.equal(requested.accepted,true);
assert.deepEqual(await sdk.requestRecovery(email,cfg.request_id),requested);
const pump=await fetch(cfg.url+'/functions/v1/squad-jobs/run',{method:'POST',headers:{Authorization:'Bearer '+cfg.worker_secret,'Content-Type':'application/json'},body:'{"limit":1}'});
assert.equal(pump.status,200);const pumped=await pump.json();assert.equal(pumped.results.length,1);assert.equal(pumped.results[0].state,'done','Mail delivery was not confirmed');
process.stdout.write(JSON.stringify({step:'mail_ready',request_id:cfg.request_id})+'\n');
const {code}=await read();assert.match(code,/^\d{8}$/);
const wrongCode=(code[0]==='0'?'1':'0')+code.slice(1);
await assert.rejects(sdk.completeRecovery({requestId:cfg.request_id,email,code:wrongCode,password:cfg.new_password}),e=>e instanceof SquadError&&e.code==='INVALID_OR_EXPIRED_CODE');
const proof={requestId:cfg.request_id,email,code,password:cfg.new_password};
const started=performance.now();const done=await sdk.completeRecovery(proof);const elapsed=performance.now()-started;
assert.equal(done.completed,true);assert.equal(done.next,'sign_in');assert.equal(done.user_id,cfg.legacy_id);
await assert.rejects(oldSdk.me(),e=>e instanceof SquadError&&['session','forbidden'].includes(e.kind));
assert.ok((await old.auth.refreshSession({refresh_token:previous.refresh_token})).error);
assert.ok((await probe.auth.signInWithPassword(cfg.customer)).error);
assert.equal((await current.auth.signInWithPassword({email,password:cfg.new_password})).error,null);
assert.equal((await createSquadClient(current).me()).id,cfg.legacy_id);
assert.deepEqual(await sdk.completeRecovery(proof),done);
assert.equal((await createSquadClient(current).me()).id,cfg.legacy_id,'A replay must not revoke the new session');
await assert.rejects(sdk.completeRecovery({...proof,password:cfg.native_password}),e=>e instanceof SquadError&&e.code==='ACCOUNT_REQUEST_CONFLICT');
const native=await current.auth.updateUser({password:cfg.native_password});assert.equal(native.error,null);
assert.deepEqual(await sdk.completeRecovery(proof),done);
assert.ok((await probe.auth.signInWithPassword({email,password:cfg.new_password})).error);
assert.equal((await probe.auth.signInWithPassword({email,password:cfg.native_password})).error,null);
await current.auth.signOut();await probe.auth.signOut();
process.stdout.write(JSON.stringify({step:'complete',environment:'staging',actual_shared_sdk:true,email_code_received:true,email_dispatched_by_edge:true,old_access_rejected:true,old_refresh_rejected:true,old_password_rejected:true,new_password_login:true,retry_preserves_new_session:true,native_password_survives_replay:true,completion_roundtrip_ms:Math.round(elapsed)})+'\n');
process.exit(0);
