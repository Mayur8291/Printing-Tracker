"""Reproducibly bundle licensed fonts without Docker-only static-file deployment."""
import base64,hashlib,json,urllib.request
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
FONTS=ROOT/'supabase/functions/squad-jobs/fonts'
def build():
 source=json.loads((FONTS/'sources.json').read_text());rows=[]
 for f in source['files']:
  local=FONTS/f['file'];data=local.read_bytes() if local.exists() else urllib.request.urlopen(f['source']).read()
  assert hashlib.sha256(data).hexdigest()==f['sha256'],'Pinned font checksum differs'
  encoded=base64.b64encode(data).decode();rows.append("'"+encoded+"'")
 body='// Generated by tools/squad/document_fonts.py. SIL OFL license and sources in fonts/.\nconst encoded = [\n'+',\n'.join(rows)+'\n];\nlet cached:Uint8Array[]|undefined;\nexport function documentFonts(){return cached??=encoded.map(x=>Uint8Array.from(atob(x),c=>c.charCodeAt(0)));}\n'
 (FONTS/'embedded.ts').write_text(body);print('Bundled pinned fonts; bytes',len(body))
if __name__=='__main__':build()
