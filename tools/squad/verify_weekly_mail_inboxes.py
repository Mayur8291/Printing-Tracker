"""Verify downloaded real inbox MIME against exact SMTP and PDF receipts."""
import argparse,hashlib,json
from email import policy
from email.parser import BytesParser
from email.utils import getaddresses
from pathlib import Path


def verify(manifest,paths):
    expected={f"<squad-business-{x['job_id']}@scottinternational.com>":x for x in manifest['deliveries']}
    assert len(expected)==5 and len(paths)==5,'Five distinct intended inbox messages required'
    seen=set();verified=[]
    for path in paths:
        assert Path(path).stat().st_size<=15*1024*1024
        data=Path(path).read_bytes();assert len(data)<=15*1024*1024
        msg=BytesParser(policy=policy.default).parsebytes(data)
        assert len(msg.get_all('Message-ID',[]))==len(msg.get_all('To',[]))==1,'Ambiguous or missing identity/recipient header'
        identity=str(msg['Message-ID']).strip();assert identity in expected and identity not in seen,'Unexpected or duplicate Message-ID'
        item=expected[identity];to=getaddresses(msg.get_all('To',[]));assert len(to)==1 and to[0][1].lower()==item['email'],'Recipient differs from server binding'
        # The trusted server-generated manifest, not a provider domain, binds
        # the intended mailbox. This verifier never authorizes or sends mail.
        text=msg.get_body(preferencelist=('plain',));assert text and item['document_id'] in text.get_content(),'Document identity absent from inbox body'
        pdf=[part for part in msg.iter_attachments() if part.get_content_type()=='application/pdf'];assert len(pdf)==1
        attachment=pdf[0].get_payload(decode=True);assert attachment.startswith(b'%PDF-')
        assert len(attachment)==item['bytes'] and hashlib.sha256(attachment).hexdigest()==item['sha256'],'Received PDF differs from generated bytes'
        seen.add(identity);verified.append({'job_id':item['job_id'],'document_id':item['document_id'],'kind':item['kind'],'recipient_role':item['role_id'],'mime_sha256':hashlib.sha256(data).hexdigest(),'attachment_sha256':item['sha256']})
    assert seen==set(expected)
    return {'inbox_verified':True,'messages':verified,'proof':'Downloaded intended-recipient inbox MIME with exact Message-ID, To, document UUID and PDF SHA256'}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('manifest',type=Path);parser.add_argument('messages',nargs=5,type=Path);a=parser.parse_args()
    result=verify(json.loads(a.manifest.read_text()),a.messages);output=a.manifest.with_name('verified-inboxes.json');output.write_text(json.dumps(result,indent=2)+'\n');output.chmod(0o600);print(json.dumps(result,indent=2))
