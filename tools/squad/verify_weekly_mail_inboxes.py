"""Verify downloaded inbox MIME against trusted recipient/document/PDF receipts.

SMTP providers may replace Message-ID. Neither a provider domain nor the
submitted identifier alone is delivery proof: every message must match one
unambiguous server-bound recipient, anchored document UUID, and exact PDF.
"""
import argparse
import hashlib
import json
import re
from email import policy
from email.parser import BytesParser
from email.utils import getaddresses
from pathlib import Path

UUID = r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
MESSAGE_ID = re.compile(r'<[^<>\s@]+@[^<>\s@]+>')


def verify(manifest, paths):
    deliveries = manifest['deliveries']
    expected = {f"<squad-business-{x['job_id']}@scottinternational.com>": x for x in deliveries}
    assert len(deliveries) == len(expected) == len(paths) == 5, 'Five distinct intended inbox messages required'
    bindings = {(x['email'], x['document_id']) for x in deliveries}
    assert len(bindings) == 5, 'Ambiguous recipient/document manifest binding'
    seen_ids, seen_jobs, verified = set(), set(), []
    for path in paths:
        assert Path(path).stat().st_size <= 15 * 1024 * 1024
        data = Path(path).read_bytes()
        assert len(data) <= 15 * 1024 * 1024
        msg = BytesParser(policy=policy.default).parsebytes(data)
        assert len(msg.get_all('Message-ID', [])) == len(msg.get_all('To', [])) == 1, 'Ambiguous or missing identity/recipient header'
        observed = str(msg['Message-ID']).strip()
        assert MESSAGE_ID.fullmatch(observed) and observed not in seen_ids, 'Malformed or duplicate received Message-ID'
        recipients = getaddresses(msg.get_all('To', []))
        assert len(recipients) == 1 and recipients[0][1], 'Ambiguous recipient'
        # Compare the full alias verbatim: never collapse plus-addresses, dots,
        # case, or provider-specific mailbox aliases to the user's base inbox.
        recipient = recipients[0][1]
        body = msg.get_body(preferencelist=('plain',))
        assert body is not None, 'Plain-text document identity absent'
        lines = [line for line in body.get_content().splitlines() if line.startswith('Document:')]
        assert len(lines) == 1 and re.fullmatch(r'Document: ' + UUID, lines[0]), 'Exactly one anchored document UUID required'
        document_id = lines[0][len('Document: '):]
        matches = [x for x in deliveries if x['email'] == recipient and x['document_id'] == document_id]
        assert len(matches) == 1, 'Recipient/document differs from server binding'
        item = matches[0]
        assert item['job_id'] not in seen_jobs, 'Duplicate intended delivery'
        submitted = f"<squad-business-{item['job_id']}@scottinternational.com>"
        # A received identifier equal to another intended job is a conflicting
        # identity, not an acceptable provider rewrite.
        assert observed not in expected or observed == submitted, 'Received Message-ID conflicts with another intended job'
        attachments = list(msg.iter_attachments())
        assert len(attachments) == 1 and attachments[0].get_content_type() == 'application/pdf', 'Exactly one PDF attachment required'
        attachment = attachments[0].get_payload(decode=True)
        assert isinstance(attachment, bytes) and attachment.startswith(b'%PDF-')
        assert len(attachment) == item['bytes'] and hashlib.sha256(attachment).hexdigest() == item['sha256'], 'Received PDF differs from generated bytes'
        seen_ids.add(observed)
        seen_jobs.add(item['job_id'])
        verified.append({
            'job_id': item['job_id'], 'document_id': item['document_id'],
            'kind': item['kind'], 'recipient_role': item['role_id'],
            'smtp_submitted_message_id': submitted,
            'inbox_observed_message_id': observed,
            'message_id_rewritten': observed != submitted,
            'mime_sha256': hashlib.sha256(data).hexdigest(),
            'attachment_sha256': item['sha256'],
        })
    assert seen_jobs == {x['job_id'] for x in deliveries}
    return {
        'inbox_verified': True, 'messages': verified,
        'proof': 'Downloaded intended-recipient inbox MIME with exact full To alias, one anchored document UUID and PDF bytes/SHA256; submitted and unique received Message-IDs recorded separately',
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('manifest', type=Path)
    parser.add_argument('messages', nargs=5, type=Path)
    args = parser.parse_args()
    result = verify(json.loads(args.manifest.read_text()), args.messages)
    output = args.manifest.with_name('verified-inboxes.json')
    output.write_text(json.dumps(result, indent=2) + '\n')
    output.chmod(0o600)
    print(json.dumps(result, indent=2))
